// ZenohServiceNaming.swift
// How wire Zenoh services are named, owned and answered the way rmw_zenoh_cpp expects.

import Foundation
import SwiftROS2Wire

#if canImport(os.log)
    import os.log
#endif

/// The ROS 2 node an entity belongs to, as rmw_zenoh_cpp writes it into the
/// entity's liveliness token.
struct ZenohNodeIdentity: Sendable, Equatable {
    /// Fully qualified namespace, `/` for the root namespace.
    let namespace: String
    let name: String
    /// The node id: every token with the same session and node id belongs to one node.
    let id: String

    /// Normalize a node namespace to rmw's form: a leading `/` and no trailing `/`.
    static func normalizedNamespace(_ namespace: String?) -> String {
        let trimmed = (namespace ?? "").split(separator: "/", omittingEmptySubsequences: true).joined(separator: "/")
        return "/" + trimmed
    }
}

/// A node this session announces: its identity, its `NN` token and how many
/// ``ZenohTransportSession/registerNode(name:namespace:)`` calls hold it.
struct ZenohNodeEntry {
    let identity: ZenohNodeIdentity
    var token: (any ZenohLivelinessTokenHandle)?
    var registrations = 0
}

/// The DDS type name and type hash a service (or one service of an action) is keyed
/// and announced with.
struct ZenohServiceNaming: Sendable, Equatable {
    let ddsTypeName: String
    let typeHash: String?
    /// The request-typed form swift-ros2 used before it carried service type hashes.
    /// Only other swift-ros2 endpoints use it; rmw_zenoh_cpp never does.
    let isLegacy: Bool

    /// rmw_zenoh_cpp names a service by its service type and the service type hash.
    /// A type generated without a service type hash (an older swift-ros2-gen) only
    /// carries its request hash: on distributions with type hashes it keeps the
    /// request-typed form, so it still reaches swift-ros2 peers that use the same
    /// type. With no hash at all, and on Humble, the service form is used.
    static func resolve(
        distro: ROS2Distro,
        serviceDDSTypeName: String,
        serviceTypeHash: String?,
        requestDDSTypeName: String,
        requestTypeHash: String?
    ) -> ZenohServiceNaming {
        guard distro.supportsTypeHash else {
            return ZenohServiceNaming(ddsTypeName: serviceDDSTypeName, typeHash: nil, isLegacy: false)
        }
        if serviceTypeHash == nil, let requestTypeHash {
            return ZenohServiceNaming(ddsTypeName: requestDDSTypeName, typeHash: requestTypeHash, isLegacy: true)
        }
        return ZenohServiceNaming(ddsTypeName: serviceDDSTypeName, typeHash: serviceTypeHash, isLegacy: false)
    }
}

/// Reports, once per type, that a service or action type has no service type hash
/// and uses the request-typed Zenoh key, which rmw_zenoh_cpp does not answer.
final class ZenohServiceHashFallbackLog: @unchecked Sendable {
    static let shared = ZenohServiceHashFallbackLog()

    private let lock = NSLock()
    private var reported: Set<String> = []

    /// Returns whether this call logged (the first report for `typeName`).
    @discardableResult
    func reportOnce(typeName: String) -> Bool {
        lock.lock()
        let isFirst = reported.insert(typeName).inserted
        lock.unlock()
        guard isFirst else { return false }
        let message =
            "\(typeName) has no service type hash (generated by an older swift-ros2-gen): "
            + "using the request-typed Zenoh key, which only swift-ros2 peers answer. "
            + "Regenerate the type to reach rmw_zenoh_cpp."
        #if canImport(os.log)
            os_log("%{public}@", log: Self.log, type: .default, message)
        #else
            FileHandle.standardError.write(Data("swift-ros2: \(message)\n".utf8))
        #endif
        return true
    }

    #if canImport(os.log)
        private static let log = OSLog(subsystem: "com.youtalk.swift-ros2", category: "Zenoh")
    #endif
}

/// The attachments of rmw_zenoh_cpp service requests and replies.
enum ZenohServiceAttachment {
    /// The attachment of a reply to a query carrying `requestAttachment`: the request's
    /// sequence number and GID with the reply's own timestamp, as rmw_zenoh_cpp's
    /// `ServiceData::send_response` writes it. rmw_zenoh_cpp clients drop a reply
    /// without one. `nil` when the request carries no rmw_zenoh attachment.
    static func reply(to requestAttachment: Data?, codec: ZenohWireCodec, tsNsec: Int64 = nowNsec()) -> Data? {
        guard let request = requestAttachment.flatMap(ZenohAttachmentFields.init) else { return nil }
        return codec.buildAttachment(seq: request.seq, tsNsec: tsNsec, gid: request.gid)
    }

    static func nowNsec() -> Int64 {
        Int64(Date().timeIntervalSince1970 * 1_000_000_000)
    }
}

/// Liveliness queries that find the service servers rmw_zenoh_cpp announces.
enum ZenohServiceDiscovery {
    /// Whether at least one `SS` token matches `queryKeyExpr` right now. `false` when
    /// the query fails or `timeoutMs` passes without a reply.
    static func anyServer(
        client: any ZenohClientProtocol,
        queryKeyExpr: String,
        timeoutMs: UInt32
    ) async -> Bool {
        await withCheckedContinuation { (cont: CheckedContinuation<Bool, Never>) in
            let state = DiscoveryProbeState(continuation: cont)
            do {
                try client.livelinessGet(
                    keyExpr: queryKeyExpr,
                    timeoutMs: timeoutMs,
                    handler: { result in
                        if case .success = result { state.resolve(true) }
                    },
                    onFinish: { state.resolve(false) }
                )
            } catch {
                state.resolve(false)
                return
            }
            // zenoh-pico may finish a liveliness query later than its timeout.
            DispatchQueue.global().asyncAfter(deadline: .now() + .milliseconds(Int(timeoutMs) + 100)) {
                state.resolve(false)
            }
        }
    }

    /// Poll every `interval` until every query in `queryKeyExprs` finds a server, or
    /// `timeout` passes. Returns whether all were found.
    static func waitForServers(
        client: any ZenohClientProtocol,
        queryKeyExprs: [String],
        timeout: Duration,
        interval: Duration = .milliseconds(100)
    ) async -> Bool {
        let clock = ContinuousClock()
        let deadline = clock.now.advanced(by: timeout)
        var pending = queryKeyExprs
        while true {
            var stillPending: [String] = []
            for key in pending {
                // Each query waits at most 1 s, and never past the deadline.
                let remaining = deadline - clock.now
                let queryMs = remaining >= .seconds(1) ? 1_000 : max(1, Int(remaining / .milliseconds(1)))
                if await !anyServer(client: client, queryKeyExpr: key, timeoutMs: UInt32(queryMs)) {
                    stillPending.append(key)
                }
            }
            pending = stillPending
            if pending.isEmpty { return true }
            if clock.now >= deadline || Task.isCancelled { return false }
            let sleep = min(interval, deadline - clock.now)
            if sleep > .zero { try? await Task.sleep(for: sleep) }
            if clock.now >= deadline { return false }
        }
    }
}

/// Resumes a discovery probe's continuation exactly once.
private final class DiscoveryProbeState: @unchecked Sendable {
    private let lock = NSLock()
    private var continuation: CheckedContinuation<Bool, Never>?

    init(continuation: CheckedContinuation<Bool, Never>) {
        self.continuation = continuation
    }

    func resolve(_ value: Bool) {
        lock.lock()
        let cont = continuation
        continuation = nil
        lock.unlock()
        cont?.resume(returning: value)
    }
}

extension Duration {
    /// The duration as a zenoh query timeout in milliseconds: negative durations are
    /// 0, and anything past `UInt32.max` milliseconds is clamped to it.
    var zenohQueryTimeoutMs: UInt32 {
        let comps = components
        let seconds = max(0, Int64(comps.seconds))
        // 1 ms == 10^15 attoseconds
        let ms = seconds.multipliedReportingOverflow(by: 1_000)
        if ms.overflow { return UInt32.max }
        let total = ms.partialValue + comps.attoseconds / 1_000_000_000_000_000
        if total < 0 { return 0 }
        if total > Int64(UInt32.max) { return UInt32.max }
        return UInt32(total)
    }
}
