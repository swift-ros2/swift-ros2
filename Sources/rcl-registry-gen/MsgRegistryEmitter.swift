/// Emits CRclBridge's name-keyed message type-support registry. Every entry resolves through
/// the rosidl C type support bundled in the RCL frameworks; Swift types are encoded by the
/// CDR codec and published through `rcl_publish_serialized_message`.
enum MsgRegistryEmitter {
    /// `crcl_marshal_registry.c`: `crcl_marshal_resolve_typesupport(name)` as one sorted
    /// `strcmp` chain.
    static func emitRegistry(_ names: [String]) -> String {
        let entries = names.sorted().map { name -> (name: String, package: String, type: String) in
            let parts = name.split(separator: "/").map(String.init)
            precondition(parts.count == 3 && parts[1] == "msg", "expected pkg/msg/Type, got \(name)")
            return (name, parts[0], parts[2])
        }
        var lines = ["// Generated by rcl-registry-gen — DO NOT EDIT.", "", "#include \"crcl_marshal.h\"", ""]
        let headers = Set(entries.map { "\($0.package)/msg/\(snakeCase($0.type)).h" })
        lines += headers.sorted().map { "#include <\($0)>" }
        lines += [
            "#include <string.h>", "",
            "const rosidl_message_type_support_t *crcl_marshal_resolve_typesupport(const char *name) {",
        ]
        for entry in entries {
            lines.append("    if (strcmp(name, \"\(entry.name)\") == 0) {")
            lines.append("        return ROSIDL_GET_MSG_TYPE_SUPPORT(\(entry.package), msg, \(entry.type));")
            lines.append("    }")
        }
        lines += ["    return NULL;", "}"]
        return lines.joined(separator: "\n") + "\n"
    }

    /// `crcl_marshal.h`: declares the resolver.
    static func emitHeader() -> String {
        """
        // Generated by rcl-registry-gen — DO NOT EDIT.

        #ifndef CRCL_MARSHAL_H
        #define CRCL_MARSHAL_H

        #include <rosidl_runtime_c/message_type_support_struct.h>

        #ifdef __cplusplus
        extern "C" {
        #endif

        const rosidl_message_type_support_t *crcl_marshal_resolve_typesupport(const char *name);

        #ifdef __cplusplus
        }
        #endif
        #endif  // CRCL_MARSHAL_H

        """
    }
}
